_AMAZON_PRODUCT_HISTORY_PATH = Path(__file__).parent / "product_history.json"
_AMAZON_COOLDOWN_DAYS = 14


_AMAZON_HISTORY_CACHE_KEY = "amazon_product_post_history"


def _load_amazon_product_history() -> list:
    """
    Amazon商品投稿履歴を読み込む。
    Supabase（content_cache）→ ローカルファイルの順で試みる。
    """
    # Supabase から読み込み（GitHub Actions間でも永続化）
    try:
        cached = db.get_content_cache(
            _AMAZON_HISTORY_CACHE_KEY,
            post_type   = "amazon_history",
            max_age_days = 90,  # 履歴は90日間保持
        )
        if cached:
            data = json.loads(cached) if isinstance(cached, str) else cached
            if isinstance(data, list):
                return data
    except Exception:
        pass

    # フォールバック: ローカルファイル
    try:
        data = json.loads(_AMAZON_PRODUCT_HISTORY_PATH.read_text(encoding="utf-8"))
        if isinstance(data, dict):
            return data.get("entries", [])
        if isinstance(data, list):
            return data
    except Exception:
        pass
    return []


def _save_amazon_product_history(entries: list) -> None:
    """
    Amazon商品投稿履歴を Supabase + ローカルファイルの両方に保存。
    どちらかが失敗してももう一方でクールダウンが効く。
    """
    # Supabase に保存（GitHub Actions間での永続化）
    try:
        db.set_content_cache(
            product_key    = _AMAZON_HISTORY_CACHE_KEY,
            source         = "amazon_post_history",
            post_type      = "amazon_history",
            generated_text = json.dumps(entries, ensure_ascii=False),
        )
    except Exception as e:
        print(f"  [AmazonPost] Supabase履歴保存失敗: {e}")

    # ローカルファイルにも保存（フォールバック用）
    try:
        _AMAZON_PRODUCT_HISTORY_PATH.write_text(
            json.dumps({"entries": entries}, ensure_ascii=False, indent=2),
            encoding="utf-8",
        )
    except Exception as e:
        print(f"  [AmazonPost] product_history 保存失敗: {e}")


def _mark_amazon_product_posted(product: dict) -> None:
    """投稿完了後にproduct_history.jsonへ記録（14日クールダウン）"""
    key = product.get("asin") or product.get("search_keyword", "")
    if not key:
        return
    entries = _load_amazon_product_history()
    now = datetime.now().isoformat()
    for e in entries:
        if e.get("key") == key:
            e["last_posted_at"] = now
            break
    else:
        entries.append({
            "key":            key,
            "title":          product.get("title", ""),
            "last_posted_at": now,
        })
    # 古いエントリを削除（30日以上前）
    cutoff = (datetime.now() - timedelta(days=30)).isoformat()
    entries = [e for e in entries if (e.get("last_posted_at") or "") >= cutoff]
    _save_amazon_product_history(entries)
    print(f"  [AmazonPost] mark_posted: {product.get('title', key)[:40]}")


def _filter_amazon_cooldown(products: list) -> list:
    """
    last_posted_at が14日以内の商品を除外して返す。
    残った商品を「未投稿 → 最古投稿」順に並べて返す（選択側がローテーションしやすくなる）。
    全件クールダウン中の場合は最古投稿順で全件返す（ランダムシャッフルは廃止）。
    """
    cutoff = (datetime.now() - timedelta(days=_AMAZON_COOLDOWN_DAYS)).isoformat()
    history = {e["key"]: e.get("last_posted_at", "") for e in _load_amazon_product_history()}

    def _sort_key(p: dict) -> str:
        key = p.get("asin") or p.get("search_keyword", "")
        # 未投稿（履歴なし）は最古扱いにして先頭へ
        return history.get(key, "0000-00-00")

    available = [
        p for p in products
        if history.get(p.get("asin") or p.get("search_keyword", ""), "") < cutoff
    ]
    if available:
        return sorted(available, key=_sort_key)

    # 全件クールダウン中 → 最古投稿を優先して全件返す（楽天と同方針）
    print("  [AmazonPost] 全商品クールダウン中 → 最古投稿を優先")
    return sorted(products, key=_sort_key)


