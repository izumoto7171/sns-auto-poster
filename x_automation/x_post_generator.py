def generate_post(force_type: str = None) -> dict:
    """投稿文を生成して返す"""
    post_type_info = pick_post_type() if not force_type else \
        next((p for p in POST_TYPES if p["type"] == force_type), POST_TYPES[0])

    post_type = post_type_info["type"]
    label     = post_type_info["label"]

    # 楽天商品紹介は専用関数で処理
    if post_type == "rakuten":
        result = generate_rakuten_product_post()
        if result:
            return result
        # 楽天失敗 → productにフォールバック
        post_type = "product"
        label = "Amazon商品紹介"

    # A8アフィリエイトは専用関数で処理
    if post_type == "a8":
        result = generate_a8_program_post()
        if result:
            return result
        # キャッシュなし → product にフォールバック
        post_type = "product"
        label = "Amazon商品紹介"

    # Amazonプール投稿（PA-APIなしで動作）: product タイプの50%で使用
    if post_type == "product" and random.random() < 0.5:
        result = generate_amazon_pool_post()
        if result:
            return result

    api_key = os.getenv("GEMINI_API_KEY")

    # 重複チェック用インデックスをロード
    full_texts, hooks = _load_dedup_index()

    # 重複していたら最大3回リトライ（Geminiの場合のみ）
    MAX_RETRY   = 3
    text        = None
    style_name  = "テンプレート"
    for attempt in range(MAX_RETRY):
        if api_key:
            candidate, style_name = generate_with_gemini(post_type, label)
        else:
            candidate  = generate_with_template(post_type)
            style_name = "テンプレート"

        hook_line = candidate.split("\n")[0].strip() if candidate else ""
        if candidate and candidate.strip() not in full_texts and hook_line not in hooks:
            text = candidate
            break
        if attempt < MAX_RETRY - 1:
            print(f"[dedup] 重複検知（{attempt + 1}回目）→ リトライ")

    # リトライ全部重複なら最後の候補をそのまま使う
    if not text:
        text = candidate if candidate else generate_with_template(post_type)

    genre = _infer_genre_from_text(text, post_type)

    return {
        "type":          post_type,
        "label":         label,
        "text":          text,
        "chars":         len(text),
        "genre":         genre,
        "writing_style": style_name,
    }


